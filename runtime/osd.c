/* Each font pixel is 4 framebuffer pixels wide (the frame is double
   horizontal resolution) and 2 lines tall, which looks square at 4:3. */
#define PX_W 4
#define PX_H 2

static void put_px(uint32_t *fb, int w, int h, int x, int y, uint32_t c) {
    for (int dy = 0; dy < PX_H; dy++)
        for (int dx = 0; dx < PX_W; dx++) {
            int xx = x + dx, yy = y + dy;
            if (xx >= 0 && xx < w && yy >= 0 && yy < h) fb[yy * w + xx] = c;
        }
}

/* draws text with its top-left corner at (x, y), with a drop shadow */
void osd_text(uint32_t *fb, int w, int h, int x, int y, const char *text) {
    for (int pass = 0; pass < 2; pass++) {
        uint32_t c = pass ? 0x00FFE070u : 0x00000000u;   /* frame pixels are 0x00RRGGBB */
        int ox = pass ? 0 : PX_W / 2, oy = pass ? 0 : PX_H / 2;
        int cx = x;
        for (const char *p = text; *p; p++) {
            const char *g = strchr(glyph_chars, toupper((unsigned char)*p));
            if (*p != ' ' && g) {
                const unsigned char *rows = glyphs[g - glyph_chars];
                for (int r = 0; r < 7; r++)
                    for (int b = 0; b < 5; b++)
                        if (rows[r] & (0x10 >> b)) put_px(fb, w, h, cx + b * PX_W + ox, y + r * PX_H + oy, c);
            }
            cx += 6 * PX_W;
        }
    }
}

int osd_text_width(const char *text) { return (int)strlen(text) * 6 * PX_W; }
