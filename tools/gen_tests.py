"""Generate per-instruction differential tests: every distinct instruction of
the module is emitted by the real code generator (with all flags live) as a
standalone C function, to be compared against the interpreter by
test/harness.c on randomized machine states."""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from analyze import load, Analysis
from gen import Gen, ALLF

SKIP = {'bsr', 'jsr', 'jmp', 'rts', 'rtr', 'rte', 'os9', 'trap', 'illegal', 'linea', 'linef',
        'stop', 'reset', 'trapv', 'chk'}


class TestGen(Gen):
    def goto(self, f, t, backward_ok=True):
        return 'return 0x%xu;' % t

    def liveness(self):
        self.live_out = {}


def main():
    import config
    from analyze import analyze_module
    an = analyze_module(config.load()['modules'][0])
    mod = an.mod
    g = TestGen(an)
    g.live_out = {a: ALLF for a in an.insns}
    seen = set()
    tests = []
    out = ['/* generated by tools/gen_tests.py */', '#include "recomp.h"', '']
    for a in sorted(an.insns):
        i = an.insns[a]
        if i.op in SKIP:
            continue
        raw = bytes(mod.data[a - mod.base:a - mod.base + i.length])
        if raw in seen:
            continue
        seen.add(raw)
        n = len(tests)
        lines = g.gen_insn(i, None)
        out.append('/* %06x: %s */' % (a, str(i).replace('*/', '* /')))
        out.append('static uint32_t T%d(void) {' % n)
        out.append('  uint32_t r_; (void)r_;')
        for l in lines:
            out.append('  ' + l)
        out.append('  return 0x%xu;' % (a + i.length))
        out.append('}')
        tests.append((a, i.length, str(i)))
    out.append('')
    out.append('typedef struct { uint32_t addr; int len; const char *text; uint32_t (*fn)(void); } InsnTest;')
    out.append('const InsnTest insn_tests[] = {')
    for n, (a, ln, txt) in enumerate(tests):
        out.append('  {0x%x, %d, "%s", T%d},' % (a, ln, txt.replace('\\', '\\\\').replace('"', '\\"'), n))
    out.append('};')
    out.append('const int insn_test_count = %d;' % len(tests))
    out.append('const uint32_t recomp_code_lo = 0x%x, recomp_code_hi = 0x%x;' % (an.code_lo, an.code_hi))
    os.makedirs('test', exist_ok=True)
    open('test/insn_tests.c', 'w').write('\n'.join(out) + '\n')
    print('generated', len(tests), 'instruction tests')


if __name__ == '__main__':
    main()
